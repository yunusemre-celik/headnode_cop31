export function detectInitialLanguage(navLang) {
  const raw =
    navLang ??
    (typeof navigator !== "undefined" ? navigator.language || "" : "");
  const primary = raw.toLowerCase().split(/[-_]/)[0];
  if (SUPPORTED_LANGUAGES.includes(primary)) {
    return primary;
  }
  return "en";
}

export function isRtlLanguage(lang) {
  return lang === "ar";
}

